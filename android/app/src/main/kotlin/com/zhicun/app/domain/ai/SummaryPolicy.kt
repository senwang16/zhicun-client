package com.zhicun.app.domain.ai

/**
 * "这段正文需不需要一份摘要"的产品判据（2026-11-05）。
 *
 * ## 为什么需要它
 * 网关提示词明确允许「资料过短或无实质内容，字段可返回空字符串或空数组」。
 * 对「买牛奶」这种 3 个字的备忘，模型返回空摘要**不是故障**，而是按契约行事；
 * 但 11-05 的空摘要修复把"有正文 + 摘要为空"一律判成失败，于是短备忘会永久挂红，
 * 点多少次"重新生成"都还是同一个合法空结果。
 *
 * 这里把"短到不需要摘要"从"上游失手"里拆出来：只有正文**达到这个长度**时，
 * 空摘要才意味着"该有却没有"，值得判失败并给用户重试入口。
 *
 * ## 为什么是 20 个字符
 * 中文里 20 字已经能表达一个完整事实（"明天下午三点在会议室开产品评审会"约 17 字），
 * 再短的多是清单项、口令、单个名词 —— 这些内容确实没有"摘要"可写。
 * 阈值同时被 `SummarizeWorker`（判成功/失败）与详情页（给不给重试入口）使用，
 * 两处必须同源，否则会出现"按钮点了还是空"。
 *
 * ## 边界
 * 按 `trim()` 后的字符数算，不区分中英文：英文 20 个字符同样能表达一个短句。
 * 这是一个产品取舍，不是模型能力边界；若将来要更精细，应由服务端下发
 * `emptyReason`（合法空 vs 上游失手），而不是继续调这个数字。
 */
object SummaryPolicy {

    /** 正文达到这个长度后，空摘要才视为"上游失手"。 */
    const val MIN_BODY_CHARS_FOR_REQUIRED_SUMMARY = 20

    /** 这段正文是否**必须**拿到摘要；false = 空摘要可以接受。 */
    fun requiresSummary(body: String): Boolean =
        body.trim().length >= MIN_BODY_CHARS_FOR_REQUIRED_SUMMARY
}